import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROTO_DIR = ROOT / "proto"
OUT_DIR = ROOT / "shared"

def main():
    OUT_DIR.mkdir(exist_ok=True)
    cmd = [
        sys.executable, "-m", "grpc_tools.protoc",
        f"-I{PROTO_DIR}",
        f"--python_out={OUT_DIR}",
        f"--grpc_python_out={OUT_DIR}",
        f"--pyi_out={OUT_DIR}",
        str(PROTO_DIR / "netwatch.proto"),
    ]
    try:
        subprocess.run(cmd, check=True)
    except subprocess.CalledProcessError as e:
        print("STDOUT:", e.stdout.decode() if e.stdout else "")
        print("STDERR:", e.stderr.decode() if e.stderr else "")
        raise

    # Fix flat import generated by protoc inside netwatch_pb2_grpc.py
    grpc_file = OUT_DIR / "netwatch_pb2_grpc.py"
    text = grpc_file.read_text()
    grpc_file.write_text(
        text.replace("import netwatch_pb2 as netwatch__pb2", "from shared import netwatch_pb2 as netwatch__pb2")
    )
    print("Generated protobuf stubs in shared/")

if __name__ == "__main__":
    main()